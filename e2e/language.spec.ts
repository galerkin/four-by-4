import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'

test('switches the whole app to English and back, keeping the choice after reload', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-11-01T12:00:00Z') })
  await page.goto('/')
  // Korean is the default.
  await expect(page.locator('html')).toHaveAttribute('lang', 'ko')
  await expect(page.getByRole('button', { name: '운동 시작', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Switch to English' }).click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await expect(page).toHaveTitle('four by four — move today')
  await expect(page.getByRole('button', { name: 'Start workout', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Warm-up' })).toBeVisible()
  await expect(page.locator('.stage-goal')).toContainText('Target 60–70% of max HR')
  await expect(page.getByRole('heading', { name: 'Today’s plan' })).toBeVisible()
  await expect(page.locator('.program-block .block-name')).toHaveText(['Warm-up', 'Hard 1', 'Active recovery', 'Hard 2', 'Active recovery', 'Hard 3', 'Active recovery', 'Hard 4', 'Cool-down'])
  await expect(page.getByText('Stop right away if you feel chest pain or dizziness')).toBeVisible()
  // The only Korean left is the switch back to Korean.
  expect((await page.locator('main').innerText()).replace('한국어', '')).not.toMatch(/[가-힣]/)

  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await page.getByRole('button', { name: 'Start workout', exact: true }).click()
  await page.clock.fastForward(600_000)
  await expect(page.getByRole('timer', { name: 'Hard 1 time remaining' })).toBeVisible()
  await expect(page.locator('.timer-next')).toContainText('Next · Active recovery')
  await page.getByRole('button', { name: 'Skip to next step' }).click()
  await expect(page.getByRole('heading', { name: 'Skip the current step?' })).toBeVisible()
  await page.getByRole('button', { name: 'Keep going' }).click()

  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  await page.getByRole('button', { name: 'Start over' }).click()
  await page.getByRole('button', { name: 'Reset', exact: true }).click()
  await page.getByRole('button', { name: 'Settings' }).click()
  await expect(page.getByRole('heading', { name: 'Fit it to your pace' })).toBeVisible()
  await page.clock.resume()
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa']).analyze()).violations).toEqual([])
  await page.getByRole('dialog').getByRole('button', { name: '한국어', exact: true }).click()
  await page.getByRole('button', { name: 'Save settings' }).click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'ko')
  await expect(page.getByRole('button', { name: '운동 시작', exact: true })).toBeVisible()
  await expect(page.getByText('내 페이스에 맞게 설정했어요.')).toBeVisible()
})

test('English library, editor and history read naturally', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Switch to English' }).click()
  await page.getByRole('button', { name: 'Programs', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'What will you do today?' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Select Norwegian 4×4' })).toContainText('40 min · 9 steps')
  await page.getByRole('button', { name: 'Copy & edit' }).click()
  await expect(page.getByLabel('Program name')).toHaveValue('Norwegian 4×4 (my copy)')
  await expect(page.getByLabel('Step 2 name')).toHaveValue('Hard 1')
  await expect(page.getByLabel('Step 2 type')).toHaveValue('work')
  await expect(page.getByLabel('Step 2 type').locator('option:checked')).toHaveText('Work')
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa']).analyze()).violations).toEqual([])
  await page.getByLabel('Program name').fill('')
  await page.getByRole('button', { name: 'Save program' }).click()
  await expect(page.getByRole('alert')).toContainText('Check the program name')
  await page.getByRole('button', { name: 'Close' }).click()
  await page.getByRole('button', { name: 'Discard changes' }).click()
  await page.getByRole('button', { name: 'History', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Waiting for your first workout.' })).toBeVisible()
})
